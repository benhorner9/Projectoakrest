const {chromium}=require('playwright');
const fs=require('node:fs'),path=require('node:path'),{spawn}=require('node:child_process');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..'),host=path.join(root,'qa','quaternius-site');
let web,browser;
(async()=>{
fs.mkdirSync(host,{recursive:true});fs.cpSync(path.join(root,'dist'),path.join(host,'oakrest-dev'),{recursive:true,force:true});
web=spawn('python3',['-m','http.server','5192','--bind','127.0.0.1'],{cwd:host,stdio:'ignore'});
await new Promise(r=>setTimeout(r,600));
browser=await chromium.launch({headless:true,args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const ctx=await browser.newContext({viewport:{width:1366,height:1024},hasTouch:true});
const page=await ctx.newPage();
const {defaultSave}=await import('../src/rules.js');
await ctx.addInitScript(d=>localStorage.setItem('oakrest-dev-v1',JSON.stringify(d)),defaultSave());
page.on('console',msg=>{if(msg.type()==='error'||msg.type()==='warning')console.log('CONSOLE',msg.type(),msg.text())});
await page.goto('http://127.0.0.1:5192/oakrest-dev/?qa=1&quaternius=1');
await page.waitForFunction(()=>window.oakrestQA?.quaterniusArt);
await page.locator('#begin').click();
await page.evaluate(()=>{oakrestQA.teleport(0,20);oakrestQA.step(1)});
await page.waitForTimeout(10000);
console.log('QUATERNIUS VISUAL STATE',JSON.stringify(await page.evaluate(()=>oakrestQA.quaterniusArt())));
await page.waitForFunction(()=>{const a=oakrestQA.quaterniusArt();return a.buildings.buildings===16&&a.town.loaded>0&&a.hero.status==='ready'&&a.monsters.some(x=>x.type==='mossling'&&x.status==='ready');},null,{timeout:75000});
const art=await page.evaluate(()=>oakrestQA.quaterniusArt());
assert.equal(art.hero.status,'ready');assert.equal(art.hero.parts,2);
assert.equal(art.buildings.buildings,16);
assert.ok(art.monsters.some(x=>x.type==='mossling'&&x.model==='mushnub'));
assert.ok(art.town.loaded<=7);assert.ok(art.town.citizens.every(c=>c.model.startsWith('peasant-')));
assert.equal((await page.evaluate(()=>oakrestQA.state().town.buildings)),16);
await page.screenshot({path:path.join(root,'qa','quaternius-village.png')});
console.log('PASS',JSON.stringify(art));
await ctx.close();
})().catch(e=>{console.error('Quaternius browser failed',e.stack);process.exitCode=1}).finally(async()=>{await browser?.close();web?.kill()});
