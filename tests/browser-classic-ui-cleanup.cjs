// iPad-sized real Chromium regression for the Director's Classic UI tidy-up.
// No production or physical Safari claims; fresh isolated browser save only.
const assert=require('node:assert/strict');
const {chromium}=require('playwright');
const {spawn}=require('node:child_process');
const {resolve}=require('node:path');
const server=spawn('python3',['-m','http.server','5295','--bind','127.0.0.1'],{cwd:resolve(__dirname,'..'),stdio:'ignore'});
let browser;
(async()=>{try{
 const {defaultSave}=await import('../src/rules.js');
 const save=defaultSave(),before=JSON.stringify(save);
 await new Promise(r=>setTimeout(r,1000));
 browser=await chromium.launch({headless:true,args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
 const ctx=await browser.newContext({viewport:{width:1194,height:834},hasTouch:true,deviceScaleFactor:1});
 await ctx.addInitScript(raw=>localStorage.setItem('oakrest-v1',raw),before);
 const page=await ctx.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:5295/classic.html?qa=1',{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>window.oakrestClassicQA,{timeout:30000});
 await page.evaluate(()=>oakrestClassicQA.pauseAutomaticLoop());
 assert.equal(await page.locator('#classic-item-window').isVisible(),true,'bag is default right panel');
 assert.equal(await page.locator('.classic-bag-tools summary').count(),0,'no extra Inventory tools disclosure');
 assert.equal(await page.getByRole('button',{name:'ARRANGE SLOTS'}).count(),0,'rearranging never requires enabling a mode');
 assert.equal(await page.getByRole('button',{name:'MAKE FROM BAG'}).count(),0);
 await page.locator('#classic-abilities-toggle').click();
 const levels=await page.locator('.oakrest-spell-tile').evaluateAll(els=>els.map(el=>Number(el.getAttribute('aria-label')?.match(/level (\d+)/)?.[1]||0)));
 assert.equal(levels.length,6);
 assert.deepEqual(levels,[...levels].sort((a,b)=>a-b),'combat abilities ordered by unlock level');
 await page.locator('#classic-skills-toggle').click();
 assert.equal(await page.locator('.classic-skill-card').count(),11);
 assert.equal(await page.locator('#classic-skill-book .classic-skill-detail').count(),0,'sidebar only lists skills');
 await page.locator('.classic-skill-card[data-skill-id=woodcutting]').tap();
 const skillPopup=page.locator('#classic-skill-popup');
 assert.equal(await skillPopup.evaluate(e=>e.open),true,'skill unlocks use a real touch-friendly modal');
 assert.ok(await skillPopup.locator('.classic-skill-unlock').count()>0);
 assert.ok(await skillPopup.locator('.future-preview').count()>0,'sealed future unlocks retained');
 await page.locator('#classic-skill-popup-close').tap();
 assert.equal(await skillPopup.evaluate(e=>e.open),false);
 assert.equal(await page.locator('#classic-skills-window').isVisible(),true,'skill cards remain in right panel');
 await page.locator('#classic-quests-toggle').click();
 assert.deepEqual(await page.locator('.oakrest-quest-group').evaluateAll(els=>els.map(e=>e.dataset.questSection)),
  ['ready','active','available','completed','locked']);
 assert.equal(await page.locator('.oakrest-quest-row').count(),8);
 await page.locator('#classic-minimap-expand').tap();
 const mapPopup=page.locator('#oakrest-world-map-popup');
 assert.equal(await mapPopup.evaluate(e=>e.open),true,'tapping minimap must open enlarged world map');
 assert.equal(await page.locator('#classic-map-canvas').isVisible(),true,'same canonical map moved to popup');
 assert.equal(await page.locator('#oakrest-atlas-picker').count(),1,'Atlas inspector retained once');
 await page.locator('#oakrest-world-map-close').tap();
 await page.waitForFunction(()=>!document.getElementById('oakrest-world-map-popup').open);
 assert.equal(await page.locator('#classic-quests-window').isVisible(),true,'close returns to previous tab');
 assert.equal(await page.locator('#classic-map-toggle').count(),1,'temporary MAP tab is retained');
 assert.equal(await page.locator('#classic-social-toggle').count(),1,'SOCIAL retained');
 await page.locator('#classic-settings-toggle').tap();
 assert.equal(await page.locator('#classic-logout').isVisible(),true);
 page.once('dialog',dialog=>dialog.accept());
 await page.locator('#classic-logout').tap();
 assert.equal(await page.locator('#classic-creator').isVisible(),true,'log out returns to character picker');
 assert.equal(await page.evaluate(()=>localStorage.getItem('oakrest-v1')),before,'log out never clears original character data');
 assert.deepEqual(errors,[]);
 console.log('PASS Classic tidy-up: direct bag tools, level-sorted combat, skill popup, quest sections, expanded minimap, guarded logout.');
}finally{await browser?.close();server.kill();}})().catch(e=>{console.error(e.stack||e);process.exitCode=1;});
